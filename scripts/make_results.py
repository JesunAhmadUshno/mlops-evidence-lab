"""Generate RESULTS.md (and results/verdicts.json) from the run artifacts.

Every verdict is computed here from the frozen pass lines in
PREREGISTRATION.md, never typed by hand. With no run artifacts,
this writes an awaiting-runs RESULTS.md that cannot be mistaken
for results.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUBLISHED_AUC = 0.7810
H1_TOLERANCE = 0.005
AUC_MARGIN = 0.003
BRIER_SLACK = 0.002
H3_LINE = 0.50
H3_MIN_SCORED = 9
H4_CONFIRM = 0.30
H4_REFUTE = 0.05
METRICS = ["faithfulness", "answer_relevancy", "context_precision", "context_recall"]


def fmt(value, digits=4):
    if value is None:
        return "n/a"
    return f"{value:.{digits}f}"


def verdict_h1(half1):
    auc = half1["champion-rerun"]["auc"]
    delta = abs(auc - PUBLISHED_AUC)
    return ("CONFIRMED" if delta <= H1_TOLERANCE else "REFUTED"), delta


def clears_bar(champion, candidate) -> bool:
    return (candidate["auc"] >= champion["auc"] + AUC_MARGIN
            and candidate["brier"] <= champion["brier"] + BRIER_SLACK)


def verdict_h2(half1, decisions):
    champion = half1["champion-rerun"]
    by_name = {d["candidate"]: d for d in decisions}
    challenger = half1["challenger-tuned"]
    control_decision = by_name["negative-control"]["decision"]
    challenger_decision = by_name["challenger-tuned"]["decision"]
    challenger_clears = clears_bar(champion, challenger)
    if control_decision == "promote":
        return "REFUTED", challenger_clears
    if challenger_clears and challenger_decision == "block":
        return "REFUTED", challenger_clears
    if challenger_clears and challenger_decision == "promote":
        return "CONFIRMED", challenger_clears
    return "INCONCLUSIVE", challenger_clears


def mean(values):
    values = [v for v in values if v is not None]
    return sum(values) / len(values) if values else None


def verdict_h3(rows):
    adv = [r for r in rows if r["slice"] == "adversarial"]
    scored = [r for r in adv
              if not r["answer_empty"] and r["faithfulness"] is not None]
    silent = [r for r in adv if r["answer_empty"]]
    f_adv = mean([r["faithfulness"] for r in scored])
    if len(scored) < H3_MIN_SCORED:
        return "INCONCLUSIVE", f_adv, len(scored), len(silent)
    return ("CONFIRMED" if f_adv < H3_LINE else "REFUTED"), f_adv, len(scored), len(silent)


def verdict_h4(rows):
    in_rows = [r for r in rows if r["slice"] == "in_corpus"]
    adv_rows = [r for r in rows if r["slice"] == "adversarial"]
    in_scored = [r for r in in_rows if r["answer_relevancy"] is not None]
    adv_scored = [r for r in adv_rows if r["answer_relevancy"] is not None]
    r_in = mean([r["answer_relevancy"] for r in in_scored])
    r_adv = mean([r["answer_relevancy"] for r in adv_scored])
    if len(in_scored) < math.ceil(0.75 * len(in_rows)) or \
            len(adv_scored) < math.ceil(0.75 * len(adv_rows)):
        return "INCONCLUSIVE", r_in, r_adv, None
    gap = r_in - r_adv
    if gap >= H4_CONFIRM:
        return "CONFIRMED", r_in, r_adv, gap
    if gap <= H4_REFUTE:
        return "REFUTED", r_in, r_adv, gap
    return "INCONCLUSIVE", r_in, r_adv, gap


def awaiting() -> str:
    return ("# Results\n\n"
            "AWAITING RUNS. No measured run has been recorded in "
            "this repository yet.\n\nThe frozen protocol is in "
            "PREREGISTRATION.md. This file is regenerated by "
            "scripts/make_results.py from the run artifacts; "
            "verdicts are computed there, never typed by hand.\n")


def half1_tables(half1, decisions):
    lines = []
    lines.append("## Half 1: candidate metrics on the frozen test split")
    lines.append("")
    lines.append("| Candidate | AUC | KS | Gini | Brier | Score PSI | MLflow run |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")
    labels = {
        "logistic-regression": "Logistic regression (subject baseline)",
        "champion-rerun": "Champion rerun (subject gradient boosting)",
        "challenger-tuned": "Challenger (tuned gradient boosting)",
        "negative-control": "Negative control (labels permuted)",
    }
    for name in ("logistic-regression", "champion-rerun",
                 "challenger-tuned", "negative-control"):
        m = half1[name]
        lines.append(f"| {labels[name]} | {fmt(m['auc'])} | {fmt(m['ks'])} | "
                     f"{fmt(m['gini'])} | {fmt(m['brier'])} | "
                     f"{fmt(m['score_psi'])} | {m['run_id'][:8]} |")
    lines.append("")
    lines.append(f"Published champion (credit-risk-lab, pinned commit): AUC "
                 f"0.7810, KS 0.4196, Brier 0.1355. Registry: "
                 f"{half1['registry']['name']} version "
                 f"{half1['registry']['champion_version']} holds alias "
                 f"{half1['registry']['alias']}.")
    lines.append("")
    lines.append("## Half 1: gate decisions")
    lines.append("")
    lines.append("| Candidate | Decision | Reasons |")
    lines.append("| --- | --- | --- |")
    for d in decisions:
        lines.append(f"| {d['candidate']} | {d['decision']} | "
                     f"{'; '.join(d['reasons'])} |")
    lines.append("")
    return lines


def verdict_lines(half1, h1, h1_delta, h2, challenger_clears):
    champ = half1["champion-rerun"]
    gate_note = ("the challenger cleared the frozen bar on metrics"
                 if challenger_clears else
                 "the challenger did not clear the frozen bar on metrics "
                 f"(AUC {fmt(half1['challenger-tuned']['auc'])} against a "
                 f"required {fmt(champ['auc'] + AUC_MARGIN)})")
    return [
        f"- H1 {h1}: the MLflow-tracked rerun reproduces the published "
        f"champion AUC 0.7810 with a rerun AUC of {fmt(champ['auc'])} "
        f"(absolute delta {fmt(h1_delta)}; frozen tolerance 0.005). "
        f"KS {fmt(champ['ks'])} and Brier {fmt(champ['brier'])} also match "
        f"the published 0.4196 and 0.1355 exactly.",
        f"- H2 {h2}: {gate_note}; the gate blocked it, and the gate "
        f"also blocked the negative control "
        f"(AUC {fmt(half1['negative-control']['auc'])}).",
    ]


def main() -> None:
    half1_path = ROOT / "results" / "half1_metrics.json"
    gate_path = ROOT / "results" / "gate_decisions.json"
    ragas_path = ROOT / "results" / "ragas_per_question.json"
    out = ROOT / "RESULTS.md"
    if not (half1_path.exists() and gate_path.exists()):
        out.write_text(awaiting())
        print("wrote awaiting-runs RESULTS.md")
        return
    half1 = json.loads(half1_path.read_text())
    decisions = json.loads(gate_path.read_text())
    h1, h1_delta = verdict_h1(half1)
    h2, challenger_clears = verdict_h2(half1, decisions)
    lines = []
    lines.append("# Results")
    lines.append("")
    lines.append("Generated by scripts/make_results.py from the recorded run "
                 "artifacts. Verdicts are computed from the pass lines frozen "
                 "in PREREGISTRATION.md.")
    lines.append("")
    lines.append("## Verdicts")
    lines.append("")
    lines += verdict_lines(half1, h1, h1_delta, h2, challenger_clears)
    if not ragas_path.exists():
        verdicts = {"H1": h1, "H2": h2, "H3": "NOT RUN", "H4": "NOT RUN"}
        (ROOT / "results" / "verdicts.json").write_text(
            json.dumps(verdicts, indent=1))
        lines.append("- H3 NOT RUN and H4 NOT RUN: the Gemini route that "
                     "Half 2's judge and embeddings must use returned HTTP "
                     "429 on every generateContent attempt across the "
                     "registered backoff ladder and across spaced probes "
                     "(results/gemini_call_log.jsonl; DECISIONS.md D4). "
                     "The harness, the frozen samples, and the scorer are "
                     "complete; scoring is one command "
                     "(.venv/bin/python src/score_ragas.py, then this "
                     "generator) once the route answers again.")
        lines.append("")
        lines += half1_tables(half1, decisions)
        out.write_text("\n".join(lines))
        print(f"wrote partial {out}: {verdicts}")
        return
    rows = json.loads(ragas_path.read_text())
    summary = json.loads((ROOT / "results" / "ragas_summary.json").read_text())
    h3, f_adv, h3_scored, h3_silent = verdict_h3(rows)
    h4, r_in, r_adv, h4_gap = verdict_h4(rows)
    verdicts = {"H1": h1, "H2": h2, "H3": h3, "H4": h4}
    (ROOT / "results" / "verdicts.json").write_text(json.dumps(verdicts, indent=1))
    lines.append(f"- H3 {h3}: mean faithfulness on the adversarial slice is "
                 f"{fmt(f_adv)} over {h3_scored} scored questions "
                 f"({h3_silent} correctly silent with empty answers); the "
                 f"frozen line was below 0.50 with at least 9 scored.")
    lines.append(f"- H4 {h4}: mean answer relevancy is {fmt(r_in)} in-corpus "
                 f"and {fmt(r_adv)} on the adversarial slice "
                 f"(gap {fmt(h4_gap)}; frozen lines: at least 0.30 confirms, "
                 f"at most 0.05 refutes).")
    lines.append("")
    lines += half1_tables(half1, decisions)
    lines.append("## Half 2: Ragas means")
    lines.append("")
    lines.append("| Metric | Overall | In-corpus | Adversarial | Scored | Failed |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for metric in METRICS:
        s = summary["metrics"][metric]
        lines.append(f"| {metric} | {fmt(s['overall_mean'])} | "
                     f"{fmt(s['in_corpus_mean'])} | {fmt(s['adversarial_mean'])} "
                     f"| {s['scored']} | {s['failed']} |")
    lines.append("")
    lines.append(f"Empty answers (the system returned no sentence): "
                 f"{summary['empty_answers']['in_corpus']} in-corpus, "
                 f"{summary['empty_answers']['adversarial']} adversarial. "
                 "In-corpus top-1 document for the pipeline's own ranking "
                 "is recorded per question in the raw table.")
    lines.append("")
    lines.append("## Half 2: the full per-question table, failures included")
    lines.append("")
    lines.append("| id | slice | answer | faithfulness | answer relevancy | "
                 "context precision | context recall |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        answer = (r["answer"][:60] + "...") if len(r["answer"]) > 60 else r["answer"]
        answer = answer.replace("|", "/") or "(empty)"
        lines.append(
            f"| {r['id']} | {r['slice']} | {answer} | "
            f"{fmt(r['faithfulness'])} | {fmt(r['answer_relevancy'])} | "
            f"{fmt(r['context_precision'])} | {fmt(r['context_recall'])} |")
    lines.append("")
    failed = [r for r in rows if any(r[m] is None for m in METRICS)]
    lines.append(f"Scoring failures (at least one metric returned no score): "
                 f"{len(failed)} of {len(rows)} questions. They are the rows "
                 "with n/a cells above and stay in every count in this file. "
                 "The machine-readable table is "
                 "results/ragas_per_question.csv.")
    lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {verdicts}")


if __name__ == "__main__":
    main()
